/**
 * 対にならなかったアスタリスクを落とす。
 * 8. **閉じないアスタリスクの後始末。** ここまでで正しく対になった太字は単一の `*` に
 *    なっているので、**2つ以上続くアスタリスクが残っていたら、それは閉じ損ねた記号**。
 *    Slack では意味を持たず、生徒の画面に記号として出るだけなので落とす。
 *
 *    なぜ個別のパターンではなく、この形にしたか（独立監査 2026-09-12・4巡目・P1）:
 *    3連を畳めば2連が残り、2連を潰せば次は別の境界値が残る、という後追いを3巡続けた。
 *    「何連か」で場合分けするのをやめ、「**対にならなかったマーカーは投稿前に落とす**」
 *    という1つの規則にしてある。トークン上限で開き `**` の直後に切れる経路
 *    （executeProcessMessage の TRUNCATED_ANSWER_NOTICE）が実運用で必ず通る。
 *
 *    残すのは**演算の対象に挟まれたもの**（`a ** 2` `１ ** ２`）だけ。
 *    `これは ** 太字のつもり ** だよ` のように隣が地の文なら落とす。Slack は
 *    `* x *` のように内側が空いた記号を強調として描かないので、残しても生徒には
 *    記号が見えるだけになる。**ここでの判定を外しても本物の太字は壊れない**
 *    （対の検出は上の flanking で既に終わっているため）。7巡目までの事故は
 *    この判定を「対の検出」に使っていたことが原因だった。
 *
 * **同じ判断を2箇所に書かないため関数にしてある**（見出しで包む前と、復元のあとの2回通す）。
 */
/** 演算の対象。**英数字だけに限る。** `_` や括弧まで含めると、`__**x` のような
 *  記号の並びを「べき乗」と読んで `**` を生徒の画面に残してしまう。
 *  空白を挟まない `2**10` は既に前段で退避済みなので、ここは空白つきの形だけを見る。 */
const OPERAND = /[A-Za-z0-9０-９]/
/** 残すと決めたべき乗の退避先。2枚目の後始末が誤って消さないようにするため */
const OPERATOR_MARK = '\u0000OPR\u0000'
function dropUnpairedBold(text: string): string {
  return text.replace(/\*{2,}/g, (m, offset: number, full: string) => {
    // 空白を挟まない `2**10` は前段（0-b）で退避済みなので、ここは空白つきだけ見る。
    const left = /(\S)[ \t]$/.exec(full.slice(0, offset))
    const right = /^[ \t](\S)/.exec(full.slice(offset + m.length))
    const isExponent = !!left && !!right && OPERAND.test(left[1]) && OPERAND.test(right[1])
    // 残すと決めたものは、2枚目の後始末が触れないように退避しておく
    return isExponent ? OPERATOR_MARK : ''
  })
}

/**
 * 標準 Markdown の記法を Slack mrkdwn に変換する。
 * 太字/見出しはプレースホルダに退避してから他の変換を通し、最後に単一アスタリスクへ復元する
 * （復元を最後に回さないと、後段の斜体変換が見出し由来のアスタリスクを誤って斜体だと解釈する）。
 */
export function convertMarkdownToMrkdwn(text: string): string {
  let out = text
  const boldPlaceholders: string[] = []
  const pushBold = (inner: string): string => {
    boldPlaceholders.push(inner)
    return `${MARK}B${boldPlaceholders.length - 1}${MARK}`
  }
  const boldTokenRe = new RegExp(`^${MARK}B(\\d+)${MARK}$`)

  // 0-a. 水平線（`***` `---` `___` だけの行）を先に処理する。
  //    Slack に水平線の記法は無い。**畳み込みより先にここで取り除かないと、
  //    `***` だけの行が `**`（閉じられない太字の記号）になって画面に残る**
  //    （独立監査 2026-09-12・3巡目・P1。畳み込みを足したこと自体が新しい穴を開けた例）。
  out = out.replace(/^[ \t]{0,3}([*\-_])[ \t]*(?:\1[ \t]*){2,}$/gm, '──────────')

  // 0-a2. **顔文字を最初に退避する。** `(*…*)` の形は、強調の規則からは見えなくする。
  //    括弧の直前直後を見るだけの守りは、**顔文字がもう1つの `*` に隣接した瞬間に破綻する**。
  //    `**(*^^*)**` では太字の正規表現が顔文字の中の `*` を跨げず一致せず、
  //    斜体の正規表現が `*(*` という意図しない短い一致を先に食べてしまい、
  //    「その `*…*` の直前直後が括弧か」という前提そのものが崩れていた
  //    （独立検査 2026-09-12・16巡目・P0。顔文字破壊の6回目）。
  //    → 括弧の内側を見るのではなく、**コードと同じように、最初に退避して隠す。**
  //
  //    【顔文字と強調を分けようとして6回失敗した記録】
  //      8巡目 かな・漢字・英数字を並べる      → ギリシャ文字が漏れた
  //      9巡目 \p{L}|\p{N}                   → 数学記号（`*×*`）が漏れた
  //     13巡目 \p{Sm}|\p{Sc} を追加            → 数学記号を使う顔文字が壊れた
  //     14巡目 構造（括弧）+ 中身の2条件        → 中身の条件がまた漏れた（ω д ﾟ ①）
  //     15巡目 条件を削って括弧だけに          → 顔文字が `**` に隣接すると破綻した
  //     16巡目 **最初に退避して隠す**（現在）
  //    **条件を足すたびに、その条件がまた漏れを持ち込んでいた。**
  //    「見てから判定する」のをやめ、「見せない」に変えたら止まった。
  //    代償: `(*大事*)` も強調にならない。Slack はこれを太字として描くので記号は出ない。
  const faces: string[] = []
  //    中身が空の `(**)` は顔文字ではない。1文字以上を要求する（要求しないと
  //    `(**)` を退避してしまい、落とすべき `**` が画面に残る）。
  out = out.replace(/[(（]\*[^*\n]+\*[)）]/g, (m) => {
    faces.push(m)
    return `${MARK}F${faces.length - 1}${MARK}`
  })

  // 0-b. **英数字に直接挟まれた `**` はべき乗として先に退避する。**
  //    `x**2+y**2=z**2` は CommonMark では語中の太字だが、中高数学の文脈では
  //    べき乗と読むのが自然。太字と読むと `x` と `2=z**2` の間が強調されて意味が変わる。
  //    プロンプトも強調には単一の `*` を使うよう指示している。
  //    対の候補から外すだけでは足りない（残った記号を後段の斜体が拾ってしまい
  //    `x*_2+y__2=z_*2` になった）。**後続のどの規則からも見えないように退避する。**
  //    ⚠️ 5〜7巡目の事故はこの「退避」の条件が緩かったこと（空白の有無・ASCII だけ）
  //    が原因だった。ここでは**英数字が直接隣接している場合だけ**に限る。
  //    `**大事**` の開きは直前が何も無いので該当せず、強調を奪わない。
  const operators: string[] = []
  out = out.replace(/(?<=[A-Za-z0-9０-９])\*{2}(?=[A-Za-z0-9０-９])/g, () => {
    operators.push('**')
    return OPERATOR_MARK
  })

  //    ※ かつてここに「3連以上のアスタリスクを ** に畳む」処理があったが削除した。
  //    `**a***b*`（太字の閉じ2つ＋斜体の開き1つ）の正当な境界を押し潰し、
  //    斜体が失われて生のアスタリスクが残っていた（独立検査 2026-09-12・11巡目・P1）。
  //    畳み込みは flanking 規則を入れる前の対症療法で、今は不要になっている。
  //    `***重要***` も `****太字****` も、flanking と後始末だけで記号が残らない。

  // 1. 太字 **text** / __text__ を退避。
  //    **改行を1つまたぐ太字も拾う**（独立監査 2026-09-12・P1）。LLM は段落全体を太字にすることがあり、
  //    改行を除外していると `**` が生徒の画面にそのまま残っていた。
  //    空行（段落の切れ目）はまたがない——またぐと、閉じ忘れた `**` が文書全体を飲み込む。
  //    **対にできるかどうかは CommonMark の flanking 規則で決める**
  //    （開きの直後と閉じの直前が空白でないこと）。
  //    これだけで `a ** 2` のべき乗は「開けも閉じもできない記号」になり、
  //    後ろにある本物の `**太字**` のマーカーを奪えなくなる。
  //    5・6・7巡目の P0 はすべて「隣の文字を見て演算子か強調かを当てる」当て推量が
  //    原因だった（空白だけで判定→強調が死ぬ→ASCII英数字で判定→全角で死ぬ）。
  //    **当てるのをやめて、記法の側の規則で決める。**
  const boldInner = String.raw`(?:[^*\n]|\n(?!\s*\n))+?`
  const underInner = String.raw`(?:[^_\n]|\n(?!\s*\n))+?`
  out = out.replace(
    new RegExp(String.raw`\*\*(?=\S)(${boldInner})(?<=\S)\*\*`, 'g'),
    (_m, inner) => pushBold(inner),
  )
  out = out.replace(
    new RegExp(String.raw`__(?=\S)(${underInner})(?<=\S)__`, 'g'),
    (_m, inner) => pushBold(inner),
  )

  // 3. 打ち消し線 ~~text~~ → Slack は単一チルダ
  //    対にならなかった `~~` は落とす（`**` と同じ扱い）。Slack は `~~` を解釈しないので、
  //    残すと生徒の画面に記号がそのまま出る（独立検査 2026-09-12・12巡目の不変条件で発見）。
  const strikethrough = (t: string) => t.replace(/~~([^~\n]+?)~~/g, '~$1~').replace(/~{2,}/g, '')
  out = strikethrough(out)

  // 4. 箇条書きの行頭記号（-, *, + + 半角スペース）→ Slack には箇条書き記法が無いので中黒にする
  out = out.replace(/^(\s*)[-*+][ \t]+(?=\S)/gm, '$1• ')

  // 5. 斜体 *text*（前後が非空白の語のみ。"3 * 4" のような掛け算は誤変換しない）→ Slack は _text_
  //    太字・見出しは 1, 2 で既に退避済みなのでここに生きた ** は残っていない
  //    ⚠️ **顔文字は 0-a2 で退避済みなので、ここでは何も判定しない。**
  //    顔文字と強調を「文字の種類」で分けようとして5回失敗した記録は 0-a2 に残してある。
  //    要点だけ: `≧` `ω` `①` は数式の内容にも顔文字の部品にもなり、
  //    **同じ文字集合を共有しているので、どんな文字集合を選んでも両立しない。**
  const italicize = (t: string) =>
    t.replace(/\*([^\s*][^*\n]*?[^\s*]|[^\s*])\*/g, (m, inner: string, offset: number, full: string) => {
      // 隣に別のアスタリスクがある候補は採らない。`**(x*y)**` のような並びで
      //    `*(x*` という短い一致を先に食べ、末尾の `**` が痕跡なく消えていた
      //    （同・16巡目・P1）。両端が `*` に接していない span だけを強調とみなす。
      if (full[offset - 1] === '*' || full[offset + m.length] === '*') return m
      // 顔文字を含むなら記号を付けない（太字側と同じ扱いにする）。
      //    片方だけ落とすと、同じ入力が場所によって違う結果になる。
      if (inner.includes(`${MARK}F`)) return inner
      const flattened = inner.replace(
        new RegExp(`${MARK}B(\\d+)${MARK}`, 'g'),
        (bm, idx) => boldPlaceholders[Number(idx)] ?? bm,
      )
      return `_${flattened}_`
    })
  out = italicize(out)

  // 5-b. **退避した太字の中身にも、同じ変換を通す。**
  //    退避は「後の変換から中身を隠す」ので、隠したままだと
  //    `**~~打ち消し~~**` の `~~` や `**a *b* c**` の `*b*` が生の記号で画面に出る
  //    （独立検査 2026-09-12・12巡目・P1/P2）。
  //    8・9・11巡目で「見出しの中」「斜体の中」と個別に手当てしてきたが、
  //    **外側がどの装飾でも、中の記法は必ず平らにする**という1つの規則にする。
  //    太字の中の太字（`**__x__**`）は重ねても意味が無いので中身だけにする。
  for (let i = 0; i < boldPlaceholders.length; i += 1) {
    const inner = boldPlaceholders[i]
    boldPlaceholders[i] = italicize(strikethrough(inner)).replace(/__([^_\n]+?)__/g, '$1')
  }

  // 6. **対にならなかったアスタリスクの後始末（1枚目）。**
  //    **見出しで包む前に通すこと。** 包んでから落とすと、見出しの中に残っていた
  //    閉じ損ねと見出し自身の記号の数が合わなくなり、**孤立した `*` が残る**
  //    （`## **閉じない太字` → `閉じない太字*`。独立検査 2026-09-12・9巡目・P1）。
  out = dropUnpairedBold(out)

  // 7. 見出し # 〜 ###### → Slack に見出し記法は無いので太字1行にする。
  //    **打ち消し線・箇条書き・斜体より後に置く。** 先に行全体を退避してしまうと、
  //    見出しの中にある `~~打ち消し~~` や `*斜体*` が変換されずに記号のまま残る
  //    （独立検査 2026-09-12・8巡目・P1）。太字だけは専用の平坦化で救っていたが、
  //    他の記法には同じ手当てが無かった——**1つの記法だけを特別扱いしたのが誤り**で、
  //    順番を変えれば全部の記法が自然に通る。
  out = out.replace(/^ {0,3}#{1,6}[ \t]+(\S.*?)[ \t]*$/gm, (_m, inner: string) => {
    const already = inner.trim().match(boldTokenRe)
    if (already) return `${MARK}B${already[1]}${MARK}`
    // 見出しは行全体が太字になるので、**中にある太字は入れ子にせず中身だけ取り出す**。
    // 入れ子のまま退避すると `*見出し *太字* です*` と二重になり、Slack では記号が見える。
    const flattened = inner.replace(
      new RegExp(`${MARK}B(\\d+)${MARK}`, 'g'),
      (m, idx) => boldPlaceholders[Number(idx)] ?? m,
    )
    return pushBold(flattened)
  })

  // 7-b. 中身が空白だけの見出し（`## ` も `##  ` も）。記号を残す意味が無いので落とす。
  //    上の見出し規則で `(\S.*?)` と書いてあるのは、`##  ` の末尾の空白を
  //    「中身」として拾ってしまい `* *` が残るのを防ぐため（同・8巡目・P2）。
  out = out.replace(/^ {0,3}#{1,6}[ \t]*$/gm, '')

  // 8. 太字プレースホルダを Slack の太字記法（単一アスタリスク）へ復元
  const restoreRe = new RegExp(`${MARK}B(\\d+)${MARK}`, 'g')
  // ⚠️ **プレースホルダは入れ子になる。** 見出しの中に太字があると
  //    （`## まとめ **大事** です`）、太字を退避した文字列ごと見出しとして
  //    もう一度退避されるため、目印の中に目印が入る。
  //    String.replace は**置換した結果を読み直さない**ので、1回だけ回すと
  //    内側の目印（制御文字）がそのまま生徒の画面に出る。安定するまで繰り返す。
  //    ⚠️ **このコメントは一度、事実と違うことを書いていた。**
  //    「現在この繰り返しはテストで到達できない」と書いていたが、それは
  //    見出しの平坦化を入れた直後の話で、その後の変更で**到達するようになっていた**のに
  //    コメントを直していなかった（独立検査 2026-09-12・21巡目・P1）。
  //    現在は上限を 1 に戻すと実テストが2件落ち、内部の目印（NUL）が出力に漏れる。
  //    **コードの近くに書いた「テストで守られていない」という主張も、変更のたびに
  //    確かめ直す。** 守られていないという記述を信じて削除されると、目印が生徒に届く。
  for (let pass = 0; pass < 10 && out.includes(`${MARK}B`); pass += 1) {
    const before = out
    // 自分が退避していない番号なら、"undefined" を出さず元の文字列のまま返す
    out = out.replace(restoreRe, (m, idx, offset: number, full: string) => {
      const inner = boldPlaceholders[Number(idx)]
      if (inner === undefined) return m
      // ⚠️ **復元で作る `*` が、地の文の `*` と隣り合うことがある。**
      //    `x*__y__`（掛け算の `*` のすぐ後ろが太字）だと `x**y*` になり、後始末が
      //    その `**` を「閉じ損ね」と読んで消し、**掛け算も強調も壊れていた**
      //    （独立検査 2026-09-12・10巡目・P1）。後始末は「地の文の記号」と
      //    「自分が作った記号」を見分けられないので、**そもそも隣り合わせない**。
      //    どちらか一方しか残せない場面では**地の文の記号を優先する**。
      //    中高数学では掛け算の記号の方が、強調より意味を持つため。
      const touchesRawAsterisk = full[offset - 1] === '*' || full[offset + m.length] === '*'
      // 顔文字を含む太字も記号を付けない。Slack は中にリテラルの `*` がある強調を
      //    正しく描けないので、包むと顔文字が崩れて見える（同・16巡目・P0）。
      const containsFace = inner.includes(`${MARK}F`)
      return touchesRawAsterisk || containsFace ? inner : `*${inner}*`
    })
    if (out === before) break
  }

  // 9. 対にならなかったアスタリスクの後始末（2枚目）。
  //    **ここでは無条件に落とす。** 残すと決めたべき乗は1枚目で退避してあるので、
  //    ここに残っている `**` は**復元で新しく隣り合ってできたもの**しかない
  //    （`__a____b__` → `*a**b*`）。1枚目と同じ判定をここでも使うと、
  //    自分が作った記号を「べき乗」と読んで残してしまう。
  //    `~~` も同じ。退避の中に隠れていたものがここで初めて表に出ることがある。
  //    ⚠️ **1回では足りない。** 片方を消すと残りが新しく隣り合うことがある
  //    （`*~~*` の `~~` を消すと `**` になる）。変化が止まるまで繰り返す。
  for (let pass = 0; pass < 5; pass += 1) {
    const before = out
    out = out.replace(/\*{2,}/g, '').replace(/~{2,}/g, '')
    if (out === before) break
  }

  // 10. 退避しておいたべき乗と顔文字を戻す
  out = out.split(OPERATOR_MARK).join('**')
  out = out.replace(new RegExp(`${MARK}F(\\d+)${MARK}`, 'g'), (m, idx) => faces[Number(idx)] ?? m)

  return out
}

/**
 * LLM 生成テキストを Slack 投稿用に整形する。呼び出し側は
 * `postMessage({ text: escapeSlackText(formatForSlack(answerText)) })` の順で使うこと
 * （escapeSlackText によるインジェクション対策は必ず最後、投稿直前に行う）。
 *
 * **べき等ではない**（既知の性質・独立監査 2026-09-12・P2）。出力の太字は Slack 記法の `*x*` だが、
 * これを再度この関数に通すと Markdown の斜体と区別できず `_x_` に化ける。単一アスタリスクが
 * 「変換済みの太字」なのか「これから変換する斜体」なのかは、文字列からは判別できない。
 * **したがって、この関数は投稿直前に1回だけ通すこと。**
 * 現在の呼び出し経路では二重適用は起きない（executeProcessMessage の ctx.resultText が
 * 保持するのは整形前の生テキストで、再配信時もそこから1回だけ整形する）。
 * 整形後のテキストを保存して再送する経路を将来作るなら、そこで必ずこの性質を確認すること。
 */
export function formatForSlack(text: string): string {
  // 目印に使う NUL を入力から除去する。表示できない制御文字なので落として実害は無く、
  // これで「入力がプレースホルダと衝突する」経路が構造的に消える（上の MARK のコメント参照）
  // 改行の表現を1つに揃える。**ここで揃えないと、以降のすべての正規表現が
  //    「改行とは何か」を各自で決めることになり、必ずどれかが漏れる。**
  //    実際、`[^*\n]` は U+2028 / U+2029 / 単体CR を「普通の文字」として通す一方、
  //    `\s` はそれらを空白として拾うため、「空行はまたがない」という守りが
  //    これらの文字では効かず、閉じ忘れの太字が後続の文まで巻き込んでいた
  //    （独立検査 2026-09-12・20巡目・P1。inspections/コード.md の「行境界文字」の項）。
  //    CRLF も LF に寄せる。Slack は LF で改行するので出力の意味は変わらない。
  const normalized = text
    .replace(/\u0000/g, '')
    .replace(/\r\n|[\r\u0085\u2028\u2029\v\f]/g, '\n')
  const { text: protectedText, restore } = protectCode(normalized)
  const withMath = convertMath(protectedText)
  const withMarkdown = convertMarkdownToMrkdwn(withMath)
  return restore(withMarkdown)
}
